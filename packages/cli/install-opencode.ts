export interface OpencodeInstallResult {
  path: string;
  /** True when bytes were written; false when the file was already current. */
  installed: boolean;
}

async function existingSymlink(path: string): Promise<boolean> {
  try {
    return (await lstat(path)).isSymbolicLink();
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return false;
    throw error;
  }
}

function isWithin(root: string, candidate: string): boolean {
  return candidate === root || candidate.startsWith(`${root}${sep}`);
}

/**
 * Install the plugin into `<projectRoot>/.opencode/plugins/subconscious.js`.
 *
 * Idempotent and byte-stable: reinstalling over unchanged state writes
 * nothing. An unrelated file at the target path is never overwritten — the
 * install fails and names the file instead. Nothing outside `.opencode/` in
 * the project, and nothing in the user's OpenCode home, is read or written.
 */
export async function installOpencode(
  projectRoot: string,
): Promise<OpencodeInstallResult> {
  const resolvedRoot = resolve(projectRoot);
  const realRoot = await realpath(resolvedRoot);
  const opencodeDirectory = join(resolvedRoot, ".opencode");
  const pluginsDirectory = join(opencodeDirectory, "plugins");
  const path = join(pluginsDirectory, "subconscious.js");
  for (const candidate of [opencodeDirectory, pluginsDirectory, path]) {
    if (await existingSymlink(candidate)) {
      throw new Error(
        `Refusing to write through symlinked OpenCode plugin path ${candidate}.`,
      );
    }
  }
  let existing: string | null = null;
  try {
    existing = await readFile(path, "utf8");
  } catch (error) {
    const code = (error as NodeJS.ErrnoException).code;
    if (code !== "ENOENT") {
      throw new Error(`Cannot read ${path}: ${(error as Error).message}`);
    }
  }
  if (existing === OPENCODE_PLUGIN_SOURCE) {
    return { path, installed: false };
  }
  if (existing !== null && !existing.startsWith(OPENCODE_PLUGIN_MARKER)) {
    throw new Error(
      `${path} exists and was not generated by Subconscious. Remove or rename it, then rerun subconscious install opencode.`,
    );
  }
  await mkdir(opencodeDirectory, { recursive: true });
  await mkdir(pluginsDirectory, { recursive: true });
  for (const candidate of [opencodeDirectory, pluginsDirectory, path]) {
    if (await existingSymlink(candidate)) {
      throw new Error(
        `Refusing to write through symlinked OpenCode plugin path ${candidate}.`,
      );
    }
  }
  const realPluginsDirectory = await realpath(pluginsDirectory);
  if (!isWithin(realRoot, realPluginsDirectory)) {
    throw new Error(
      `Refusing to write outside the project root through ${pluginsDirectory}.`,
    );
  }
  await atomicWriteFile(path, OPENCODE_PLUGIN_SOURCE);
  return { path, installed: true };
}

/**
 * Dispatch entry matching the other installers' shape. Only `opencode` is
 * accepted here; the shared installer routes before calling.
 */
export async function installAdapter(
  harness: KnownHarnessId,
  projectRoot: string,
): Promise<string> {
  if (harness !== "opencode") {
    throw new Error(`Unsupported harness adapter: ${harness}`);
  }
  const result = await installOpencode(projectRoot);
  return result.installed
    ? `Installed the Subconscious plugin at ${result.path}.`
    : `The Subconscious plugin is already installed at ${result.path}.`;
}
