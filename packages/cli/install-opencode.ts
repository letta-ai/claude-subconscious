/**
 * The generated OpenCode plugin.
 *
 * Installation is project-local by design: OpenCode auto-discovers
 * `.opencode/plugins/*.js`, so one self-contained file is the whole
 * integration. The file owns every native hook, speaks newline-delimited JSON
 * to the hidden `subconscious opencode-bridge` subprocess found on PATH, and
 * never imports anything from the Subconscious package. No runtime
 * dependency installation and no absolute worktree paths. If PATH has no
 * `subconscious` binary, the plugin warns once at startup and stays idle.
 *
 * Delivery contract implemented here (see SPEC):
 * - Prompt-boundary passive context happens in `chat.message`, where one
 *   synthetic text part carries the combined status/whisper block after the
 *   original prompt is observed. Mid-turn passive context stays in
 *   `experimental.chat.system.transform`, where one whisper block is appended
 *   to `output.system` and existing entries are never replaced.
 * - Leasing goes through the bridge; the mutation happens here; the
 *   acknowledgement is a second, separate bridge call. A missing session,
 *   project, or broker means no mutation and no acknowledgement.
 * - Observations await only a bounded local transcript fetch plus a durable
 *   broker enqueue through the bridge. Observer work is never awaited.
 */

